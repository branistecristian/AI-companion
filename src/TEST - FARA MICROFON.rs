/// Draw a 16×16 bitmap scaled ×2 (→ 32×32) at the given top-left corner.
fn blit_2x(
    disp: &mut impl DrawTarget<Color = BinaryColor>,
    bitmap: &[u8; 32],
    tl: Point,                 // top–left
) -> Result<(), core::convert::Infallible> {
    let style = PrimitiveStyle::with_fill(BinaryColor::On);

    for (row, chunk) in bitmap.chunks(2).enumerate() {
        // each `chunk` = 16 bits = 2 bytes = one row
        let bits = u16::from_be_bytes([chunk[0], chunk[1]]);
        for col in 0..16 {
            if bits & (1 << (15 - col)) != 0 {
                // draw a 2×2 “pixel”
                Rectangle::new(
                    tl + Point::new(col as i32 * 2, row as i32 * 2),
                    Size::new(2, 2),
                )
                .into_styled(style)
                .draw(disp)
                .ok();
            }
        }
    }
    Ok(())
}

